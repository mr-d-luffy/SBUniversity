/**
 * SiliconBrains University Frontend API Client
 * Typed fetch wrapper for the FastAPI backend (/api/v1) with support for Clerk JWTs and Dev Bypass Tokens.
 */
export function getBaseUrl(): string {
  const configuredUrl = process.env.NEXT_PUBLIC_API_BASE_URL;
  if (process.env.NODE_ENV !== "production") {
    return configuredUrl?.startsWith("/")
      ? configuredUrl.replace(/\/+$/, "")
      : "/api/local-backend";
  }

  const defaultUrl =
    configuredUrl ??
    "https://sbuniversity.onrender.com/api/v1";
  if (defaultUrl.startsWith("/")) {
    return defaultUrl.replace(/\/+$/, "");
  }

  try {
    const url = new URL(defaultUrl);
    if (typeof window !== "undefined") {
      if (url.hostname === "0.0.0.0" || url.hostname === "::") {
        url.hostname = window.location.hostname || "localhost";
      }
      if (window.location.hostname === "127.0.0.1" && url.hostname === "localhost") {
        url.hostname = "127.0.0.1";
      } else if (window.location.hostname === "localhost" && url.hostname === "127.0.0.1") {
        url.hostname = "localhost";
      }
    }
    const path = url.pathname.replace(/\/+$/, "");
    if (!path.endsWith("/api/v1")) {
      url.pathname = `${path}/api/v1`;
    }
    return url.toString().replace(/\/$/, "");
  } catch {
    // Fall back to the configured value if it is not an absolute URL.
  }
  return defaultUrl;
}

export class ApiError extends Error {
  constructor(public status: number, message: string) {
    super(message);
    this.name = "ApiError";
  }
}

/**
 * Executes a typed request to the FastAPI backend with optional Bearer authentication.
 */
export async function api<T>(
  path: string,
  token?: string,
  init: RequestInit = {}
): Promise<T> {
  const headers = new Headers(init.headers);
  if (!headers.has("Content-Type") && !(init.body instanceof FormData)) {
    headers.set("Content-Type", "application/json");
  }
  if (token) {
    headers.set("Authorization", `Bearer ${token}`);
  }

  const base = getBaseUrl();
  let res: Response;
  try {
    res = await fetch(`${base}${path}`, {
      ...init,
      headers,
    });
  } catch (error) {
    if (error instanceof TypeError) {
      throw new Error(
        `Unable to connect to the API at ${base}. Check that the backend is running and NEXT_PUBLIC_API_BASE_URL is reachable from this browser.`,
        { cause: error }
      );
    }
    throw error;
  }

  if (!res.ok) {
    const errorBody = await res.json().catch(() => null);
    const message =
      (typeof errorBody?.detail === "string" ? errorBody.detail : null) ||
      errorBody?.detail?.error?.message ||
      errorBody?.error?.message ||
      res.statusText ||
      `Request failed with status ${res.status}`;
    throw new ApiError(res.status, message);
  }

  if (res.status === 204) {
    return undefined as T;
  }

  return res.json() as Promise<T>;
}

/**
 * Downloads a binary PDF stream generated by the backend and opens it directly in a new tab.
 */
export async function downloadAndOpenPdf(path: string, filename: string, token?: string): Promise<void> {
  const base = getBaseUrl();
  const urlWithToken = token 
    ? `${base}${path}${path.includes("?") ? "&" : "?"}token=${encodeURIComponent(token)}`
    : `${base}${path}`;

  try {
    const headers = new Headers();
    if (token) {
      headers.set("Authorization", `Bearer ${token}`);
    }
    const res = await fetch(`${base}${path}`, { headers });
    if (res.ok) {
      const blob = await res.blob();
      const pdfBlob = new Blob([blob], { type: "application/pdf" });
      const blobUrl = URL.createObjectURL(pdfBlob);

      // Open PDF in a new browser tab
      window.open(blobUrl, "_blank");

      // Direct download trigger
      const anchor = document.createElement("a");
      anchor.href = blobUrl;
      anchor.download = filename;
      document.body.appendChild(anchor);
      anchor.click();
      document.body.removeChild(anchor);
      return;
    }
  } catch (err) {
    console.warn("Direct blob download failed, falling back to window.open", err);
  }

  // Fallback: Open in new window directly
  window.open(urlWithToken, "_blank");
}

/**
 * Downloads a binary PDF stream generated by the backend (ReportLab Result Statement or Certificate).
 */
export async function downloadPdf(path: string, filename: string, token?: string): Promise<void> {
  await downloadAndOpenPdf(path, filename, token);
}

/**
 * Returns a dev-bypass token for local development when DEMO mode is enabled.
 */
export function getDevAuthToken(role: "student" | "teacher" | "admin" = "student"): string {
  switch (role) {
    case "teacher":
      return "dev-token-teacher-u_teacher";
    case "admin":
      return "dev-token-admin-u_admin";
    default:
      return "dev-token-student-u_student1";
  }
}
